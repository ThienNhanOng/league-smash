"""Generates src/Generated/Sheets.g.cs from sheets/*.json: one C# definition per sheet row, built from its columns."""
import json, os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
def load(n): return json.load(open(os.path.join(ROOT, 'sheets', n + '.json'), encoding='utf-8'))['rows']

def s(v): return json.dumps(v)
def f(v): return repr(float(v)) + 'f'
def arr(xs): return 'new string[] {' + ', '.join(s(x) for x in xs) + '}'
def dct(d): return 'new Dictionary<string, string> {' + ', '.join('{' + s(k) + ', ' + s(v) + '}' for k, v in d.items()) + '}'

champs, anims, abil, clips, effects, passives = load('champions'), load('animations'), load('abilities'), load('slap_clips'), load('effects'), load('passives')
pass_by = {p['champion']: p for p in passives}
fighters = {r['id']: r for r in load('slap_fighters')}
objects = load('objects')
def en(eid): return 'Effect.' + eid.title().replace('_', '')
anim_by = {a['champion']: a for a in anims}
roles = [k for k in anims[0] if k != 'champion']

out = ['// <auto-generated> by tools/gen.py from sheets/*.json. Edit the sheets, not this file. </auto-generated>',
       'using System.Collections.Generic;', '', 'namespace SlapRift.Generated', '{']
out.append('    public enum Effect { ' + ', '.join(e['id'].title().replace('_', '') for e in effects) + ' }')
out.append('    public enum Role { ' + ', '.join(r.title() for r in roles) + ' }')
out.append('''
    public sealed class AbilityDef
    {
        public string Champion, Slot, Key, Name, Sfx, Vo, SfxProc; public Role Role; public float Dmg, Kb; public EffectUse[] Effects;
        public float Get(Effect e) { foreach (var u in Effects) if (u.Effect == e) return u.Value; return 0f; }
        public bool Has(Effect e) { foreach (var u in Effects) if (u.Effect == e) return true; return false; }
    }

    public struct EffectUse { public Effect Effect; public float Value; }

    public sealed class ObjectDef
    {
        public string Id, Champion, Slot, Kind, Model, Mesh, Tex, SfxSpawn, SfxHit; public bool Third;
        public float Forward, Life, Radius, Speed, Size, Dmg, BaseKb, KbGain, Angle, Slow;
    }

    public sealed class PassiveDef
    {
        public string Name, Sfx; public Effect Effect; public float Value;
    }

    public sealed class ClipRule
    {
        public string Pattern, Special; public Role Role; public float Speed; public bool Loop, Sync;
    }

    public sealed class ChampionDef
    {
        public string Id, Name, Wad, VoWad, Base, Skn, Skl, Tex, Icon, Portrait, SfxBank, SfxEvents, VoAudio, VoEvents, VoSelect, VoKO, VoTaunt;
        public int Slot; public float Height, Yaw;
        public Dictionary<string, string> TexBySubmesh; public string[] HideSubmeshes;
        public Dictionary<Role, string> Anims;
        public Dictionary<string, string> SpecialMoves;
        public AbilityDef Neutral, Side, Up, Down; public PassiveDef Passive;
        public string AnimPath(Role r) => "assets/characters/" + Id.Substring(4) + "/skins/base/animations/" + Anims[r] + ".anm";
    }

    public static class Sheets
    {''')

for a in abil:
    v = f"Ab_{a['champion'][4:]}_{a['slot']}"
    out.append(f"        static readonly AbilityDef {v} = new AbilityDef {{ Champion = {s(a['champion'])}, Slot = {s(a['slot'])}, Key = {s(a['key'])}, Name = {s(a['ability'])}, "
               f"Role = Role.{a['role'].title()}, Sfx = {s(a['sfx'])}, Vo = {s(a['vo'])}, SfxProc = {s(a['sfxProc'])}, "
               f"Dmg = {f(a['dmg'])}, Kb = {f(a['kb'])}, Effects = new[] {{ " + ", ".join(f"new EffectUse {{ Effect = {en(e.split(':')[0])}, Value = {f(e.split(':')[1])} }}" for e in a['effects']) + " } };")

out.append('\n        public static readonly ChampionDef[] Champions = {')
for c in sorted(champs, key=lambda c: c['slot']):
    an = anim_by[c['id']]; n = c['id'][4:]
    out.append(f"""            new ChampionDef {{
                Id = {s(c['id'])}, Name = {s(c['name'])}, Wad = {s(c['wad'])}, VoWad = {s(c['voWad'])}, Base = {s(c['base'])}, Slot = {c['slot']},
                Skn = {s(c['skn'])}, Skl = {s(c['skl'])}, Tex = {s(c['tex'])}, TexBySubmesh = {dct(c['texBySubmesh'])}, HideSubmeshes = {arr(c['hideSubmeshes'])},
                Icon = {s(c['icon'])}, Portrait = {s(c['portrait'])}, Height = {f(c['height'])}, Yaw = {f(c['yaw'])},
                SfxBank = {s(c['sfxBank'])}, SfxEvents = {s(c['sfxEvents'])}, VoAudio = {s(c['voAudio'])}, VoEvents = {s(c['voEvents'])},
                VoSelect = {s(c['voSelect'])}, VoKO = {s(c['voKO'])}, VoTaunt = {s(c['voTaunt'])},
                SpecialMoves = {dct(fighters[c['base']]['moves'])},
                Anims = new Dictionary<Role, string> {{ {', '.join('{Role.' + r.title() + ', ' + s(an[r]) + '}' for r in roles)} }},
                Neutral = Ab_{n}_neutral, Side = Ab_{n}_side, Up = Ab_{n}_up, Down = Ab_{n}_down,
                Passive = new PassiveDef {{ Name = {s(pass_by[c['id']]['passive'])}, Effect = {en(pass_by[c['id']]['effect'])}, Value = {f(pass_by[c['id']]['value'])}, Sfx = {s(pass_by[c['id']]['sfx'])} }}
            }},""")
out.append('        };')

out.append('\n        public static readonly ObjectDef[] Objects = {')
for o in objects:
    slot, _, cond = o['trigger'].partition(':')
    out.append(f"            new ObjectDef {{ Id = {s(o['id'])}, Champion = {s(o['champion'])}, Slot = {s(slot)}, Third = {str(cond == 'third').lower()}, Kind = {s(o['kind'])}, Model = {s(o['model'])}, Mesh = {s(o['mesh'])}, Tex = {s(o['tex'])}, "
               f"Forward = {f(o['forward'])}, Life = {f(o['life'])}, Radius = {f(o['radius'])}, Speed = {f(o['speed'])}, Size = {f(o['size'])}, Dmg = {f(o['dmg'])}, BaseKb = {f(o['basekb'])}, KbGain = {f(o['kbgain'])}, Angle = {f(o['angle'])}, Slow = {f(o['slow'])}, "
               f"SfxSpawn = {s(o['sfxSpawn'])}, SfxHit = {s(o['sfxHit'])} }},")
out.append('        };')
out.append('\n        public static readonly ClipRule[] Clips = {')
for r in clips:
    special = r['role'][1:] if r['role'].startswith('@') else None
    role = 'Idle' if special else r['role'].title()
    out.append(f"            new ClipRule {{ Pattern = {s(r['pattern'])}, Role = Role.{role}, Special = {s(special) if special else 'null'}, Speed = {f(r['speed'])}, Loop = {str(r['loop']).lower()}, Sync = {str(r['sync']).lower()} }},")
out.append('        };')
out.append('    }\n}\n')

dst = os.path.join(ROOT, 'src', 'Generated', 'Sheets.g.cs')
os.makedirs(os.path.dirname(dst), exist_ok=True)
open(dst, 'w', encoding='utf-8', newline='\n').write('\n'.join(out))
print('wrote', dst, len(champs), 'champions', len(abil), 'abilities', len(clips), 'clip rules')
